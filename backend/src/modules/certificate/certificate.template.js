const PDFDocument = require('pdfkit');
const QRCode = require('qrcode');

const BRAND_RED = '#C0392B';
const BRAND_DARK = '#2C3E50';
const LIGHT_GRAY = '#ECF0F1';

const generatePdfBuffer = async (cert, donation, donor, hospital) => {
  const qrDataUrl = await QRCode.toDataURL(cert.qrPayload, { width: 120, margin: 1 });
  const qrBuffer = Buffer.from(qrDataUrl.split(',')[1], 'base64');

  return new Promise((resolve, reject) => {
    const doc = new PDFDocument({ size: 'A4', margin: 50 });
    const buffers = [];

    doc.on('data', (b) => buffers.push(b));
    doc.on('end', () => resolve(Buffer.concat(buffers)));
    doc.on('error', reject);

    // Header bar
    doc.rect(0, 0, doc.page.width, 80).fill(BRAND_RED);
    doc.fillColor('white').fontSize(26).font('Helvetica-Bold')
      .text('BloodLink', 50, 25);
    doc.fontSize(12).font('Helvetica')
      .text('Certificate of Blood Donation', 50, 52);

    // Title
    doc.fillColor(BRAND_DARK).fontSize(20).font('Helvetica-Bold')
      .text('DONATION CERTIFICATE', { align: 'center' })
      .moveDown(0.5);

    doc.moveTo(50, doc.y).lineTo(doc.page.width - 50, doc.y)
      .strokeColor(BRAND_RED).lineWidth(2).stroke().moveDown(1);

    // Body
    doc.fontSize(12).font('Helvetica').fillColor(BRAND_DARK);

    const row = (label, value) => {
      doc.font('Helvetica-Bold').text(`${label}: `, { continued: true })
        .font('Helvetica').text(value).moveDown(0.4);
    };

    row('Donor Name', donor.name);
    row('Blood Group', donation.donationType === 'WHOLE_BLOOD'
      ? `${donor.bloodGroup} (Whole Blood)`
      : `${donor.bloodGroup} (${donation.donationType})`);
    row('Units Donated', String(donation.units));
    row('Date of Donation', new Date(donation.donatedAt).toDateString());
    row('Hospital', `${hospital.name}, ${hospital.address}`);
    row('Certificate No.', cert.verificationId);
    row('Issued On', new Date(cert.issuedAt).toDateString());

    doc.moveDown(1);
    doc.fontSize(10).fillColor('#7F8C8D')
      .text('Verify this certificate at:', { align: 'center' })
      .text(cert.qrPayload, { align: 'center' })
      .moveDown(0.5);

    // QR code
    doc.image(qrBuffer, (doc.page.width - 100) / 2, doc.y, { width: 100 });
    doc.moveDown(6);

    // Footer
    doc.fontSize(9).fillColor('#95A5A6')
      .text('This certificate is auto-generated by BloodLink and is digitally verifiable.', {
        align: 'center',
      });

    doc.end();
  });
};

module.exports = { generatePdfBuffer };
